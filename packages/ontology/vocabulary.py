def vocabulary_content_hash() -> str:
    """어휘 전체의 정규화 해시. 버전 문자열과 별개로 내용 변경을 드러낸다."""

    canonical = json.dumps(
        {
            "version": VOCABULARY_VERSION,
            "types": [
                {
                    "typeId": definition.type_id,
                    "nameKo": definition.name_ko,
                    "descriptionKo": definition.description_ko,
                    "keywords": list(definition.keywords),
                }
                for definition in VOCABULARY
            ],
            "fallbackTypes": [
                {"typeId": type_id, "keywords": list(keywords)}
                for type_id, keywords in FALLBACK_VOCABULARY
            ],
            "directionTokens": {
                "up": list(UP_DIRECTION_TOKENS),
                "down": list(DOWN_DIRECTION_TOKENS),
                "mixed": list(MIXED_DIRECTION_TOKENS),
            },
            "certaintyMarkers": {
                "anticipation": list(ANTICIPATION_MARKERS),
                "confirmed": list(CONFIRMED_MARKERS),
            },
            "continuationMarkers": list(CONTINUATION_MARKERS),
        },
        ensure_ascii=False,
        sort_keys=True,
        separators=(",", ":"),
    )
    return hashlib.sha256(canonical.encode("utf-8")).hexdigest()
